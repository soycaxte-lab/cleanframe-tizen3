/* Compile the unsupported CSS features for the Tizen 3 runtime. */
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');
const root = path.resolve(__dirname, '..');
const source = postcss.parse(fs.readFileSync(path.join(root, 'app/style.css'), 'utf8'));
const affected = new Set(['row-gap', 'column-gap']);
source.walkDecls(d => { if (!d.prop.startsWith('--') && d.value.includes('var(')) affected.add(d.prop); });
const rules = [];
let order = 0;
function specificity(selector) {
  // Current source uses :not(simple-class) and no :is/:where/selector lists inside functions.
  const s = selector.replace(/:not\(/g, '(').replace(/::[\w-]+/g, ' T');
  const ids = (s.match(/#[\w-]+/g) || []).length;
  const classes = (s.match(/\.[\w-]+|\[[^\]]+\]|:(?!:)[\w-]+/g) || []).length;
  const tags = (s.replace(/#[\w-]+|\.[\w-]+|\[[^\]]+\]|:(?!:)[\w-]+/g, '').match(/(?:^|[\s>+~(])([a-zA-Z][\w-]*)/g) || []).length;
  return ids * 1000000 + classes * 1000 + tags;
}
source.walkRules(rule => {
  const media = [];
  let parent = rule.parent;
  while (parent && parent.type !== 'root') {
    if (parent.type === 'atrule' && parent.name === 'media') media.unshift(parent.params);
    parent = parent.parent;
  }
  const decls = [];
  rule.walkDecls(d => {
    if (d.prop.startsWith('--') || affected.has(d.prop)) decls.push([d.prop, d.value, !!d.important, order++]);
    if (d.prop === 'gap') {
      const values = postcss.list.space(d.value);
      decls.push(['row-gap', values[0], !!d.important, order++], ['column-gap', values[1] || values[0], !!d.important, order++]);
    }
  });
  if (decls.length) postcss.list.comma(rule.selector).forEach(selector => {
    if (selector.includes(':focus-visible')) return;
    const pseudo = selector.match(/::?(before|after)\s*$/);
    rules.push({selector:pseudo ? selector.slice(0, pseudo.index) : selector,
      pseudo:pseudo ? '::' + pseudo[1] : '', specificity:specificity(selector), media, declarations:decls});
  });
});
const legacy = source.clone();
legacy.walkDecls(d => {
  if (d.prop.startsWith('--') || d.value.includes('var(') || ['gap','row-gap','column-gap'].includes(d.prop)) { d.remove(); return; }
  if (d.prop === 'inset') {
    const v = postcss.list.space(d.value);
    const values = [v[0],v[1]||v[0],v[2]||v[0],v[3]||v[1]||v[0]];
    ['top','right','bottom','left'].forEach((prop,i) => d.cloneBefore({prop,value:values[i]}));
    d.remove();
  }
});
legacy.walkRules(r => { if (r.selector.includes(':focus-visible')) r.remove(); });
fs.writeFileSync(path.join(root,'app/style-tizen3.css'),
  '/* Generated by scripts/build-tizen3.cjs. Do not edit. */\n' + legacy.toString() +
  '\nhtml.cf-tizen3:not(.cf-tizen3-ready) .stage{visibility:hidden}\n');
fs.writeFileSync(path.join(root,'app/tizen3-rules.js'),
  '/* Generated from style.css; runtime values are resolved on UI updates only. */\nwindow.CleanFrameLegacyRules=' + JSON.stringify(rules) + ';\n');
console.log('Tizen 3: ' + rules.length + ' selector rules compiled; CSS var(), gap and inset removed.');
